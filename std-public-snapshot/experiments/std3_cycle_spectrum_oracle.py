#!/usr/bin/env python3
"""Independent bounded literal oracle for STD3 issue #108.

The direct path enumerates every rooted source word and never uses the cycle
classification or a source-length divisibility argument. A separate graph
path reconstructs recurrent cycles and evaluates the *candidate* formula.
These finite checks are not a universal mathematical proof.

Reproduce from repository root:
    python experiments/std3_cycle_spectrum_oracle.py --output /tmp/std3.json
    python -O experiments/std3_cycle_spectrum_oracle.py --output /tmp/std3-opt.json
    cmp /tmp/std3.json /tmp/std3-opt.json
"""

import argparse
from collections import Counter, defaultdict
from itertools import combinations, product
from math import lcm
import json
from pathlib import Path

PINNED_MAIN = "private-history-omitted"
SCHEMA = "std3-literal-cycle-spectrum-v1"

# These are small, declared source presentations, NOT generated by any theorem.
# 'seeds' generate explicit allowed m-windows; optional extras are transient.
FIXTURES = (
    dict(name="pr100_identity", alphabet="01", m=7,
         seeds=("0011", "000111"), extras=(), radius=0,
         rule="identity", orders=(2,), max_n=12),
    dict(name="binary_variable_emission", alphabet="01", m=4,
         seeds=("0011", "01"), extras=(), radius=1,
         rule="double_ones", orders=(1, 2, 3, 4), max_n=12),
    dict(name="higher_order_separation", alphabet="01", m=7,
         seeds=("0000101", "0001001"), extras=(), radius=0,
         rule="identity", orders=(1, 2, 3, 4), max_n=12),
    dict(name="short_period_radius_two", alphabet="01", m=3,
         seeds=("001", "1"), extras=(), radius=2,
         rule="neighbor_sensitive", orders=(1, 2, 3), max_n=12),
    dict(name="transient_noncyclic_edge", alphabet="01", m=2,
         seeds=("0", "1"), extras=("01",), radius=0,
         rule="double_zero", orders=(1, 2), max_n=12),
    dict(name="ternary_variable_emission", alphabet="012", m=2,
         seeds=("01", "2"), extras=(), radius=1,
         rule="ternary_vary", orders=(1, 2, 3, 4), max_n=8),
    dict(name="single_primitive_cycle", alphabet="01", m=3,
         seeds=("001",), extras=(), radius=0,
         rule="double_ones", orders=(1, 2, 3), max_n=12),
    dict(name="unary_short_wrap", alphabet="0", m=1,
         seeds=("0",), extras=(), radius=2,
         rule="unary_xy", orders=(1, 2, 5), max_n=8),
)


def windows_modulo(word, order):
    """Enumerate exactly len(word) periodic windows; works when order > length."""
    if not word or not isinstance(order, int) or order < 1:
        raise ValueError("nonempty word and positive window length required")
    return ["".join(word[(i + j) % len(word)] for j in range(order))
            for i in range(len(word))]


def counts_via_padding(word, order):
    """Second, separately coded cyclic counter for the density path."""
    if not word or not isinstance(order, int) or order < 1:
        raise ValueError("nonempty word and positive order required")
    padded = word * ((order + len(word) - 1) // len(word) + 1)
    return Counter(padded[i:i + order] for i in range(len(word)))


def counter_key(counter):
    return tuple(sorted(counter.items()))


def allowed_words(fixture):
    allowed = set(fixture["extras"])
    for seed in fixture["seeds"]:
        if not seed or any(letter not in fixture["alphabet"] for letter in seed):
            raise ValueError("invalid fixture seed")
        allowed.update(windows_modulo(seed, fixture["m"]))
    return tuple(sorted(allowed))


def direct_admissible(word, allowed, m):
    """Literal periodic window membership; no graph, cycle, or orbit shortcut."""
    return all(window in allowed for window in windows_modulo(word, m))


def rooted_domain(alphabet, allowed, m, n):
    if n < 1:
        raise ValueError("length must be positive")
    allowed = set(allowed)
    words = ("".join(letters) for letters in product(alphabet, repeat=n))
    return [word for word in words if direct_admissible(word, allowed, m)]


def rule_table(alphabet, radius, rule):
    """Materialize a total deterministic context table, including unused contexts."""
    if radius < 0:
        raise ValueError("negative radius")
    table = {}
    for chars in product(alphabet, repeat=2 * radius + 1):
        ctx = "".join(chars)
        center = ctx[radius]
        if rule == "identity":
            emission = center
        elif rule == "double_ones":
            emission = "11" if center == "1" else "0"
        elif rule == "neighbor_sensitive":
            emission = "01" if center == "0" else ("1" if ctx[0] == "0" else "00")
        elif rule == "double_zero":
            emission = "00" if center == "0" else "1"
        elif rule == "ternary_vary":
            emission = {"0": "ab", "1": "b", "2": "a"}[center]
        elif rule == "unary_xy":
            emission = "xy"
        else:
            raise ValueError("unknown emission rule: " + rule)
        if not emission:
            raise ValueError("nonerasing emission required")
        table[ctx] = emission
    return table


def transform_literal(word, radius, table):
    """Synchronous cyclic site-by-site concatenation, retaining the chosen root."""
    if not word:
        raise ValueError("empty input is out of scope")
    pieces = []
    for site in range(len(word)):
        context = "".join(word[(site + j) % len(word)]
                          for j in range(-radius, radius + 1))
        if context not in table or not isinstance(table[context], str) or not table[context]:
            raise ValueError("missing or empty context emission")
        pieces.append(table[context])
    return "".join(pieces)


def recurrent_cycles(allowed, alphabet, m):
    """Check complete recurrent graph by reachability, then extract simple cycles.

    A length-m word e is a directed edge e[:-1] -> e[1:]. Such an edge
    belongs to a directed closed walk iff its destination can reach its
    origin. Transient edges are excluded independently of any fixture seeds.
    """
    if m < 1 or not alphabet or len(set(alphabet)) != len(alphabet):
        raise ValueError("invalid alphabet or graph order")
    if not allowed or any(len(e) != m or any(a not in alphabet for a in e)
                          for e in allowed):
        raise ValueError("invalid allowed-window support")
    if len(set(allowed)) != len(allowed):
        raise ValueError("duplicate edge type")
    adjacency = defaultdict(list)
    for edge in allowed:
        adjacency[edge[:-1]].append(edge[1:])

    def reaches(start, target):
        todo, visited = [start], set()
        while todo:
            v = todo.pop()
            if v == target:
                return True
            if v not in visited:
                visited.add(v)
                todo.extend(adjacency[v])
        return False

    recurrent = tuple(sorted(e for e in allowed if reaches(e[1:], e[:-1])))
    if not recurrent:
        raise ValueError("no recurrent edges: all fixed-length domains empty")
    incoming, outgoing = defaultdict(list), defaultdict(list)
    for edge in recurrent:
        outgoing[edge[:-1]].append(edge)
        incoming[edge[1:]].append(edge)
    vertices = set(incoming) | set(outgoing)
    if any(len(incoming[v]) != 1 or len(outgoing[v]) != 1 for v in vertices):
        raise ValueError("recurrent graph is not disjoint simple directed cycles")
    unseen = set(vertices)
    cycles = []
    while unseen:
        start = min(unseen)
        here, chars, edges = start, [], []
        while here in unseen:
            unseen.remove(here)
            edge = outgoing[here][0]
            edges.append(edge)
            chars.append(edge[-1])
            here = edge[1:]
        if here != start:
            raise ValueError("recurrent successor did not close at the start")
        word = "".join(chars)
        if set(windows_modulo(word, m)) != set(edges):
            raise ValueError("graph/source cyclic-label inconsistency")
        if any(len(word) % p == 0 and word == word[:p] * (len(word) // p)
               for p in range(1, len(word))):
            raise ValueError("simple graph cycle labeled by nonprimitive word")
        cycles.append({"word": word, "period": len(word), "edges": tuple(sorted(edges))})
    return tuple(sorted(cycles, key=lambda c: (c["period"], c["word"]))), recurrent


def hypothesized_sources(cycles, n):
    """Candidate source-orbit classification; never used by literal horizon."""
    sources = set()
    for cycle in cycles:
        d = cycle["period"]
        if n % d == 0:
            repeated = cycle["word"] * (n // d)
            sources.update(repeated[i:] + repeated[:i] for i in range(d))
    return sources


def density_equal(a, da, b, db):
    """Exact rational equality with integer cross-multiplication, no floats."""
    return all(a.get(t, 0) * db == b.get(t, 0) * da for t in set(a) | set(b))


def candidate_horizon(cycles, n, radius, table, k, m):
    """Independently compute the #104 pairwise *proposed* density formula."""
    active = [c for c in cycles if n % c["period"] == 0]
    if not active:
        return None
    target = {c["word"]: counts_via_padding(
        transform_literal(c["word"], radius, table), k) for c in active}
    for h in range(1, m + 1):
        source = {c["word"]: counts_via_padding(c["word"], h) for c in active}
        if all(not density_equal(source[x["word"]], x["period"],
                                 source[y["word"]], y["period"])
               or density_equal(target[x["word"]], x["period"],
                                target[y["word"]], y["period"])
               for x, y in combinations(active, 2)):
            return h
    return None


def direct_horizon(words, radius, table, k, m):
    """Brute-force exact horizon on the listed rooted domain; no predictor use."""
    if not words:
        return None, None
    outputs = {w: counter_key(Counter(windows_modulo(
        transform_literal(w, radius, table), k))) for w in words}
    first_failure = None
    for h in range(1, m + 1):
        encountered = {}
        collision = None
        for word in words:
            key = counter_key(Counter(windows_modulo(word, h)))
            earlier = encountered.get(key)
            if earlier is not None and outputs[earlier] != outputs[word]:
                collision = {"h": h, "left": earlier, "right": word}
                break
            if earlier is None:
                encountered[key] = word
        if collision is None:
            return h, first_failure
        if first_failure is None:
            first_failure = collision
    return None, first_failure


def check_repeat_rotation(cycles, radius, table, orders):
    """Directly test emission-period scaling and root rotation of small cycles."""
    checks = 0
    for cycle in cycles:
        w = cycle["word"]
        once = transform_literal(w, radius, table)
        for multiple in (2, 3):
            repeated = transform_literal(w * multiple, radius, table)
            if repeated != once * multiple:
                raise ValueError("emission repetition failure: " + w)
            for k in orders:
                left = Counter(windows_modulo(repeated, k))
                right = Counter(windows_modulo(once, k))
                if left != Counter({key: multiple * count for key, count in right.items()}):
                    raise ValueError("output histogram scale failure: " + w)
                checks += 1
        for site in range(1, len(w)):
            rotated = w[site:] + w[:site]
            output = transform_literal(rotated, radius, table)
            if len(output) != len(once) or output not in once + once:
                raise ValueError("unequal-length output rotation failure: " + w)
            checks += 1
    return checks


def run_experiments():
    report = {"schema": SCHEMA, "pinned_main": PINNED_MAIN,
              "evidence": "bounded exhaustive rooted-word enumeration; not theorem proof",
              "fixtures": [], "totals": {"rooted_words_considered": 0,
                                        "rooted_words_admitted": 0,
                                        "lengths_checked": 0,
                                        "nonempty_horizon_checks": 0,
                                        "all_horizon_checks": 0,
                                        "rotation_and_repetition_checks": 0,
                                        "repeated_nonempty_residue_checks": 0,
                                        "disagreements": 0}}
    totals = report["totals"]
    for spec in FIXTURES:
        allowed = allowed_words(spec)
        cycles, recurrent = recurrent_cycles(allowed, spec["alphabet"], spec["m"])
        table = rule_table(spec["alphabet"], spec["radius"], spec["rule"])
        checked = check_repeat_rotation(cycles, spec["radius"], table, spec["orders"])
        totals["rotation_and_repetition_checks"] += checked
        fixture_report = {"name": spec["name"], "alphabet": spec["alphabet"],
                          "m": spec["m"], "allowed": allowed,
                          "recurrent": recurrent, "seeds": spec["seeds"],
                          "radius": spec["radius"], "rule": spec["rule"],
                          "table": table, "orders": spec["orders"],
                          "cycles": cycles, "lcm_periods": lcm(*(c["period"] for c in cycles)),
                          "max_n": spec["max_n"], "lengths": []}
        for n in range(1, spec["max_n"] + 1):
            rooted = rooted_domain(spec["alphabet"], allowed, spec["m"], n)
            orbit = hypothesized_sources(cycles, n)
            if set(rooted) != orbit:
                left = sorted(set(rooted) - orbit)
                right = sorted(orbit - set(rooted))
                raise ValueError("source-orbit classification differs at {} N={}: direct_only={}, predictor_only={}".format(
                    spec["name"], n, left[:1], right[:1]))
            row = {"n": n, "considered": len(spec["alphabet"]) ** n,
                   "admitted": len(rooted), "active_periods":
                   [c["period"] for c in cycles if n % c["period"] == 0],
                   "horizons": {}}
            totals["rooted_words_considered"] += row["considered"]
            totals["rooted_words_admitted"] += row["admitted"]
            totals["lengths_checked"] += 1
            for k in spec["orders"]:
                h, first_failure = direct_horizon(rooted, spec["radius"],
                                                  table, k, spec["m"])
                predicted = candidate_horizon(cycles, n, spec["radius"],
                                              table, k, spec["m"])
                if h != predicted:
                    raise ValueError("horizon disagreement at {} N={} k={}: literal {}, density {}; first failure {}".format(
                        spec["name"], n, k, h, predicted, first_failure))
                if rooted and h is None:
                    raise ValueError("no horizon <=m at {} N={} k={}".format(spec["name"], n, k))
                row["horizons"][str(k)] = {"literal": h, "candidate": predicted,
                                          "first_failed_h": first_failure}
                totals["all_horizon_checks"] += 1
                if rooted:
                    totals["nonempty_horizon_checks"] += 1
            fixture_report["lengths"].append(row)
        # Check observable periodicity only where two nonempty enumerated lengths
        # share a residue. No claim is made for empty-length horizons.
        seen_residues = {}
        for row in fixture_report["lengths"]:
            if not row["admitted"]:
                continue
            residue = row["n"] % fixture_report["lcm_periods"]
            profile = tuple((k, result["literal"]) for k, result in
                            sorted(row["horizons"].items()))
            if residue in seen_residues:
                if seen_residues[residue] != profile:
                    raise ValueError("horizon changes within a residue: " + spec["name"])
                totals["repeated_nonempty_residue_checks"] += 1
            seen_residues[residue] = profile
        report["fixtures"].append(fixture_report)
    report["negative_fixtures"] = negative_regressions()
    return report


def negative_regressions():
    """A branching/shared-vertex support must not be silently treated as cycles."""
    violations = (
        ("branching_m2", ("00", "01", "10"), "01", 2, "001"),
        ("shared_vertex_m3", ("000", "001", "010", "100"), "01", 3, "001"),
    )
    results = []
    for name, allowed, alphabet, m, witness in violations:
        if not direct_admissible(witness, set(allowed), m):
            raise ValueError("negative fixture lost admissible counterexample")
        try:
            recurrent_cycles(allowed, alphabet, m)
        except ValueError as exc:
            results.append({"name": name, "admissible_word": witness,
                            "precondition": "REJECTED", "reason": str(exc)})
        else:
            raise ValueError("negative recurrent branching fixture not rejected")
    for name, allowed, alphabet, m in (
        ("bad_window_length", ("00", "1"), "01", 2),
        ("bad_alphabet", ("00", "22"), "01", 2),
        ("empty_recurrent_core", ("01",), "01", 2),
    ):
        try:
            recurrent_cycles(allowed, alphabet, m)
        except ValueError as exc:
            results.append({"name": name, "precondition": "REJECTED", "reason": str(exc)})
        else:
            raise ValueError("negative malformed support not rejected: " + name)
    try:
        transform_literal("0", 0, {"0": ""})
    except ValueError as exc:
        results.append({"name": "erasing_rule_excluded", "precondition": "REJECTED",
                        "reason": str(exc)})
    else:
        raise ValueError("erasing emission was accepted")
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        help="write deterministic UTF-8 JSON, otherwise print")
    arguments = parser.parse_args()
    serialized = json.dumps(run_experiments(), sort_keys=True, indent=2) + "\n"
    if arguments.output:
        arguments.output.write_text(serialized, encoding="utf-8")
    else:
        print(serialized, end="")


if __name__ == "__main__":
    main()
